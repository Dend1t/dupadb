--1.
--         Напишите запрос к таблице SUBJECT, выводящий для каждой ее
--         строки идентификатор (номер) предмета обучения, его наименование,
--         семестр, в котором он читается, и количество отводимых на него часов.
SELECT *
FROM subject;

--2.
--        Напишите запрос, позволяющий вывести все строки таблицы EXAM_MARKS,
--        в которых предмет обучения имеет номер (SUBJ_ID), равный 12.

SELECT *
FROM subject
WHERE subj_ID=12;

--3.
--        Напишите запрос, выбирающий все данные из таблицы STUDENT,
--        расположив столбцы таблицы в следующем порядке:
--        KURS, SURNAME, NAME, STIPEND.

SELECT KURS, SURNAME, NAME, STIPEND
FROM student;

--4.
--        Напишите запрос SELECT, который для каждого предмета обучения (SUBJECT)
--        выполняет вывод его наименования (SUBJ_NAME)
--        и следом за ним количества часов (HOUR) в 4-м семестре (SEMESTER).

SELECT subj_name, hour, semester
FROM subject;

--5.
--        Напишите запрос, позволяющий получить из таблицы
--        EXAM_MARKS значения столбца MARK (экзаменационная оценка)
--        для всех студентов, исключив из списка повторение одинаковых строк.

SELECT DISTINCT mark
FROM exam_marks;



--6. !!!
--        Напишите запрос, который выполняет вывод списка фамилий
--        студентов, обучающихся на третьем и более старших курсах.

SELECT surname
FROM student
WHERE kurs >=3;

--7.
--        Напишите запрос, выбирающий данные фамилию, имя и номер
--        курса для студентов, получающих стипендию больше 140.

SELECT *
FROM student
WHERE stipend >= 140;

--8. !!!
--        Напишите запрос, выполняющий выборку из таблицы SUBJECT
--        названий всех предметов обучения, на которые отводится более 30 часов.

SELECT *
FROM subject
WHERE hour>30;

--9.
--        Напишите запрос, который выполняет вывод списка университетов,
--        рейтинг которых превышает 300 баллов.

SELECT *
FROM university
WHERE rating>30;

--10.
--        Напишите запрос к таблице STUDENT для вывода списка всех
--        студентов со стипендией не меньше 100, живущих в Воронеже —
--        с указанием фамилии (SURNAME), имени (NAME) и номера курса (KURS).

SELECT *
FROM student
WHERE stipend>=100 AND city ='Воронеж' ;

