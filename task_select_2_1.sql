WHERE birthday >  CURRENT_DATE - INTERVAL '25 years' AND kurs=1;

--14. !!!
--        Напишите запрос для получения списка предметов, для которых
--        в 1-м семестре отведено более 100 часов.

SELECT *
FROM subject
WHERE semester=1 AND hour>100;

--15. !!!
--        Напишите запрос для получения списка преподавателей, живущих в Воронеже.

SELECT *
FROM lecturer
WHERE city ='Воронеж' ;

--16. !!!
--        Напишите запрос для получения списка университетов,
--        расположенных в Москве и имеющих рейтинг меньший, чем у ВГУ.
--        Константу в ограничении на рейтинг можно определить по этой же таблице.

SELECT *
FROM university
WHERE city = 'Москва' AND rating < (SELECT rating FROM university WHERE univ_name LIKE 'Воронежский г%');

--17. !!!
--        Напишите запрос для получения списка студентов,
--        проживающих в Воронеже и не получающих стипендию.

SELECT *
FROM student
WHERE (stipend IS NULL or stipend = 0) AND NOT city ='Воронеж';

--18. ?   WHERE birthday  CURRENT_DATE - INTERVAL '20 years';
--        Напишите запрос для получения списка студентов моложе 20 лет.

SELECT *
FROM student
WHERE birthday < CURRENT_DATE - INTERVAL '20 years';

--19. !!!
--        Напишите запрос для получения списка студентов без определенного места жительства.

SELECT *
FROM student
WHERE city IS NULL;

