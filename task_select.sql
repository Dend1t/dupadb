--1.?
--        Напишите запрос, выполняющий вывод находящихся в таблице
--        EXAM_MARKS номеров предметов обучения, экзамены по которым
--        сдавались между 10 и 20 января 2005 г.

SELECT DISTINCT sub.subj_id, subj_name
FROM exam_marks em
JOIN subject sub ON em.subj_id = sub.subj_id
WHERE exam_date BETWEEN '2000-03-01' AND '2000-03-31' ;

--2.?
--        Напишите запрос, выбирающий данные обо всех предметах обучения,
--        экзамены по которым сданы студентами, имеющими идентификаторы 12 и 32.

SELECT DISTINCT sub.subj_id, subj_name
FROM exam_marks em
JOIN subject sub ON em.subj_id = sub.subj_id
WHERE student_id IN (12,32);

