--3. !!!
--       Составьте запрос для таблицы STUDENT таким образом,
--       чтобы выходная таблица содержала всего один столбец в следующем виде:
--
--       б.кузнецов; место жительства - брянск; - родился: 8-дек-1987.

SELECT lower(substr(name,1,1) || '.' || surname ||  '; место жительства - ' || city || '; - родился: ' || to_char(birthday, 'dd-mon-yyyy')) AS dupa
FROM student ;

--4. !!!
