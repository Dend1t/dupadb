--1. !!!
--       Составьте запрос для таблицы STUDENT таким образом, чтобы
--       выходная таблица содержала один столбец, содержащий последовательность
--       разделенных символом “;” (точка с запятой) значений всех столбцов этой таблицы;
--       при этом текстовые значения должны отображаться
--       прописными символами (верхний регистр),
--       т.е. быть представленными в следующем виде:
--
--       10;КУЗНЕЦОВ;БОРИС;0;БРЯНСК; 8.12.1987;10.

SELECT upper(student_id || ';' || surname || ';' || stipend || ';' || city || ';' || to_char(birthday, 'dd.mm.yy') || ';' || univ_id) AS dupa
FROM student ;

--2. !!!
--       Составьте запрос для таблицы STUDENT таким образом,
